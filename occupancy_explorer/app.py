"""
Occupancy explorer (Streamlit)

What this app does:
- Pulls occupancy events from the read-only GraphQL API (source-graphql) into
  a local Parquet cache, fetching only what's new on each sync.
- Summarizes every location: how many events, over what span, and whether the
  count adds up (a running count below zero means the sensor missed people).
- For one location: occupancy over time, entries and exits per bucket, a
  weekday x hour profile, day-by-day drift, and upload lag.
- A GraphQL tab to run your own queries against the same API.

The data model in one line: occupancy = running sum of delta (+1 enter, -1 leave).
Times are stored in UTC and shown in America/Denver wall-clock time.
"""
import json
import os
from datetime import timedelta

import altair as alt
import pandas as pd
import streamlit as st
from occupancy_api import CACHE, GraphQLError, graphql, load_config, read_cache, sync

from eda import (
    bucketed,
    daily_drift,
    is_synthetic,
    late_arrivals,
    local_naive,
    location_summary,
    upload_lag,
    weekday_hour_profile,
)

st.set_page_config(page_title="Occupancy explorer", layout="wide")
st.title("Occupancy explorer")

# ========== Connection ==========
config = load_config()
url = os.environ.get("OCCUPANCY_GRAPHQL_URL") or config.get("graphql_url", "")
key = os.environ.get("OCCUPANCY_GRAPHQL_KEY", "")
if not key:
    try:
        key = st.secrets.get("graphql_key", "")
    except FileNotFoundError:          # no .streamlit/secrets.toml
        key = ""
    except Exception:                  # malformed secrets.toml
        key = ""
connected = bool(url and key)


def run_sync(full: bool = False) -> None:
    try:
        stats = sync(url, key, full=full)
        st.session_state["last_sync"] = stats
        st.session_state.pop("sync_error", None)
    except GraphQLError as e:
        st.session_state["sync_error"] = str(e)


@st.cache_data(show_spinner=False)
def load_events(mtime: float) -> pd.DataFrame:
    """Read the cache. `mtime` is only a cache key: a new sync -> a new file -> a fresh read."""
    return read_cache()


# ========== Sidebar: sync ==========
st.sidebar.header("Data")
if not connected:
    st.sidebar.error("No API key. Set OCCUPANCY_GRAPHQL_KEY or add graphql_key to "
                     "occupancy_explorer/.streamlit/secrets.toml (see README).")
else:
    if "last_sync" not in st.session_state and "sync_error" not in st.session_state:
        with st.spinner("Fetching new events..."):
            run_sync()                  # once per browser session
    c1, c2 = st.sidebar.columns(2)
    if c1.button("Fetch new", help="Ask the API for events newer than the cache"):
        with st.spinner("Fetching new events..."):
            run_sync()
    if c2.button("Re-read all", help="Ignore the cache and download everything again"):
        with st.spinner("Downloading every event..."):
            run_sync(full=True)
if "sync_error" in st.session_state:
    st.sidebar.warning(f"Sync failed, showing the cached data: {st.session_state['sync_error']}")
elif "last_sync" in st.session_state:
    s = st.session_state["last_sync"]
    st.sidebar.caption(f"Last sync: {s['new']} new, {s['total']} cached "
                       f"({s['fetched']} rows read, overlap included).")

events = load_events(CACHE.stat().st_mtime if CACHE.exists() else 0.0)
if events.empty:
    st.info("No events cached yet. Connect to the API (sidebar) and fetch.")
    st.stop()

# ========== Sidebar: what to look at ==========
st.sidebar.header("View")
show_mock = st.sidebar.checkbox("Include mock- locations", value=True,
                                help="Mock locations are synthetic: generated by ingress-mock")
summary = location_summary(events)
if not show_mock:
    summary = summary[~summary["synthetic"]]
if summary.empty:
    st.info("Only mock locations so far. Tick 'Include mock- locations' to see them.")
    st.stop()
by_events = summary.sort_values("events", ascending=False)["location"].tolist()
location = st.sidebar.selectbox("Location", by_events, help="Sorted by number of events")

loc_events = events[events["location"] == location]
first_day = local_naive(loc_events["ts"]).min().date()
last_day = local_naive(loc_events["ts"]).max().date()
start_default = max(first_day, last_day - timedelta(days=13))
picked = st.sidebar.date_input("Dates (local)", value=(start_default, last_day),
                               min_value=first_day, max_value=last_day)
start_day, end_day = (picked if isinstance(picked, tuple) and len(picked) == 2
                      else (start_default, last_day))
bucket_label = st.sidebar.selectbox("Bucket", ["15 min", "1 hour", "1 day"], index=1)
freq = {"15 min": "15min", "1 hour": "1h", "1 day": "1D"}[bucket_label]

# ========== Tabs ==========
tab_all, tab_loc, tab_gql = st.tabs(["All locations", f"Location: {location}", "GraphQL"])

with tab_all:
    m1, m2, m3 = st.columns(3)
    m1.metric("Events", f"{len(events):,}")
    m2.metric("Locations", f"{events['location'].nunique()}")
    m3.metric("Real (non-mock) events",
              f"{int((~events['location'].map(is_synthetic)).sum()):,}")
    display = summary.copy()
    for col in ("first", "last"):
        display[col] = local_naive(display[col])
    st.dataframe(display, hide_index=True, width="stretch", column_config={
        "lowest_count": st.column_config.NumberColumn(
            help="Below zero: more people left than entered. The sensor missed some entries."),
        "median_lag_s": st.column_config.NumberColumn(
            format="%.1f", help="Median seconds from the event to the server storing it"),
    })
    st.caption("count_now is the sum of every delta. For a real room at night it should be 0; "
               "anything else is accumulated counting error.")

with tab_loc:
    if is_synthetic(location):
        st.warning(f"**{location}** is synthetic (ingress-mock). Don't train on it as if it were real.")

    # Running counts are computed over *all* of this location's events and only then cut to the
    # date range: occupancy at 9am depends on everything that happened before 9am.
    buckets = bucketed(loc_events, freq)
    window = buckets.loc[str(start_day):str(end_day)]

    lag = upload_lag(loc_events)
    m1, m2, m3, m4 = st.columns(4)
    m1.metric("Events in range", f"{int(window['enters'].sum() + window['leaves'].sum()):,}")
    m2.metric("Count now", f"{int(loc_events['delta'].sum())}")
    m3.metric("Peak in range", f"{int(window['occupancy'].max()) if not window.empty else 0}")
    m4.metric("Late arrivals", f"{late_arrivals(loc_events):,}",
              help="Events the server received after a later-timestamped event")

    if window.empty:
        st.info("No buckets in this date range.")
    else:
        frame = window.reset_index()
        st.markdown(f"**Occupancy at the end of each {bucket_label} bucket**")
        st.altair_chart(
            alt.Chart(frame).mark_line(interpolate="step-after").encode(
                x=alt.X("time:T", title="Local time"),
                y=alt.Y("occupancy:Q", title="People"),
                tooltip=["time:T", "occupancy:Q", "enters:Q", "leaves:Q"],
            ).properties(height=240)
            + alt.Chart(pd.DataFrame({"y": [0]})).mark_rule(color="#999", strokeDash=[4, 4])
            .encode(y="y:Q"),
            width="stretch")

        st.markdown(f"**Entries (up) and exits (down) per {bucket_label}**")
        flows = frame.assign(exits=-frame["leaves"]).melt(
            id_vars="time", value_vars=["enters", "exits"], var_name="direction", value_name="n")
        st.altair_chart(
            alt.Chart(flows).mark_bar().encode(
                x=alt.X("time:T", title="Local time"),
                y=alt.Y("n:Q", title="Events"),
                color=alt.Color("direction:N", scale=alt.Scale(
                    domain=["enters", "exits"], range=["#2a9d8f", "#e76f51"])),
                tooltip=["time:T", "direction:N", alt.Tooltip("n:Q", format="d")],
            ).properties(height=200),
            width="stretch")

    left, right = st.columns(2)
    with left:
        st.markdown("**Typical week: mean entries per local hour**")
        profile = weekday_hour_profile(loc_events)
        if profile.empty:
            st.info("Not enough data for a weekly profile.")
        else:
            st.altair_chart(
                alt.Chart(profile).mark_rect().encode(
                    x=alt.X("hour:O", title="Hour"),
                    y=alt.Y("weekday_name:N", title=None,
                            sort=["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]),
                    color=alt.Color("mean_enters:Q", title="Entries/h",
                                    scale=alt.Scale(scheme="blues")),
                    tooltip=["weekday_name:N", "hour:O",
                             alt.Tooltip("mean_enters:Q", format=".2f")],
                ).properties(height=220),
                width="stretch")
            st.caption("Averaged over every hour in the data, including empty ones.")
    with right:
        st.markdown("**Daily drift: net change per local day**")
        drift = daily_drift(loc_events)
        drift = drift[(drift["date"].dt.date >= start_day) & (drift["date"].dt.date <= end_day)]
        if drift.empty:
            st.info("No days in this range.")
        else:
            st.altair_chart(
                alt.Chart(drift).mark_bar().encode(
                    x=alt.X("date:T", title="Day"),
                    y=alt.Y("net:Q", title="Enters - leaves"),
                    color=alt.condition("datum.net == 0", alt.value("#bbb"), alt.value("#e76f51")),
                    tooltip=["date:T", "net:Q", "end_of_day:Q"],
                ).properties(height=220),
                width="stretch")
            bad = int((drift["net"] != 0).sum())
            st.caption(f"{bad} of {len(drift)} days don't net to zero. A room that empties at "
                       "night should, so each red bar is a counting error.")

    st.markdown("**Upload lag: seconds from event to server**")
    if lag.empty:
        st.info("No events.")
    else:
        clipped = lag.assign(lag_s=lag["lag_s"].clip(-60, 3600))
        st.altair_chart(
            alt.Chart(clipped).mark_bar().encode(
                x=alt.X("lag_s:Q", bin=alt.Bin(maxbins=60), title="Lag (s, clipped to -60..3600)"),
                y=alt.Y("count():Q", title="Events"),
            ).properties(height=180),
            width="stretch")
        st.caption(f"Median {lag['lag_s'].median():.1f} s, max {lag['lag_s'].max():,.0f} s. "
                   "Near zero: posted live. Minutes: the Pi's 2-minute cron. Hours or days: "
                   "an outage caught up, or a backfill.")

    with st.expander("Raw events (most recent 200 in range)"):
        raw = loc_events.assign(ts=local_naive(loc_events["ts"]),
                                received_at=local_naive(loc_events["received_at"]))
        raw = raw[(raw["ts"].dt.date >= start_day) & (raw["ts"].dt.date <= end_day)]
        st.dataframe(raw.sort_values(["ts", "row_id"]).tail(200),
                     hide_index=True, width="stretch")

EXAMPLES = {
    "Latest 10 events": ("""query Latest {
  occupancyEvents(first: 10, orderBy: [ROW_ID_DESC]) {
    totalCount
    nodes { rowId location ts delta eventId receivedAt }
  }
}""", {}),
    "One location, one day": ("""query OneDay($location: String!, $from: Datetime!, $to: Datetime!) {
  occupancyEvents(
    orderBy: [TS_ASC, ROW_ID_ASC]
    filter: { location: { equalTo: $location }, ts: { greaterThanOrEqualTo: $from, lessThan: $to } }
  ) {
    totalCount
    nodes { ts delta eventId }
  }
}""", {"location": None, "from": None, "to": None}),
    "Look up by record key": ("""query ByKey($location: String!, $eventId: String!) {
  occupancyEventByLocationAndEventId(location: $location, eventId: $eventId) {
    rowId ts delta receivedAt
  }
}""", {"location": None, "eventId": None}),
    "Schema: event fields": ("""query Fields {
  __type(name: "OccupancyEvent") { fields { name type { name kind ofType { name } } } }
}""", {}),
}

with tab_gql:
    st.markdown("Run any query against the API. It is **read-only**: mutations are rejected. "
                "Pages are capped at 5000 rows and queries at 5 levels deep. "
                f"For autocomplete and docs, open the API's own explorer: [Ruru]({url.rsplit('/graphql', 1)[0]}/)."
                if url else "No API URL configured.")
    example = st.selectbox("Start from an example", list(EXAMPLES))
    query_text, variables = EXAMPLES[example]
    # Fill example variables from the current selection so the examples run as-is.
    last = loc_events.sort_values("row_id").iloc[-1]
    defaults = {"location": location, "eventId": str(last["event_id"]),
                "from": pd.Timestamp(start_day, tz="America/Denver").isoformat(),
                "to": pd.Timestamp(start_day + timedelta(days=1), tz="America/Denver").isoformat()}
    variables = {k: defaults.get(k, v) for k, v in variables.items()}
    query = st.text_area("Query", query_text, height=220, key=f"q_{example}")
    vars_text = st.text_area("Variables (JSON)", json.dumps(variables, indent=2),
                             height=110, key=f"v_{example}_{location}_{start_day}")
    if st.button("Run query", disabled=not connected):
        try:
            result = graphql(url, key, query, json.loads(vars_text or "{}"), retries=1)
            st.json(result)
            nodes = next((v["nodes"] for v in result.values()
                          if isinstance(v, dict) and isinstance(v.get("nodes"), list)), None)
            if nodes:
                st.markdown(f"**{len(nodes)} nodes as a table**")
                st.dataframe(pd.DataFrame(nodes), hide_index=True, width="stretch")
        except json.JSONDecodeError as e:
            st.error(f"Variables aren't valid JSON: {e}")
        except GraphQLError as e:
            st.error(str(e))

st.caption("Data: occupancy-backend source-graphql (read-only). "
           "Occupancy = running sum of delta. Times shown in America/Denver.")
